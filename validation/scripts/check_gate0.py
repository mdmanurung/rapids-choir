#!/usr/bin/env python3
"""Fail-closed Gate 0 verification."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

EXPECTED_FIXTURES = {
    "batch_eligibility.json",
    "batch_positional_metrics.json",
    "decision_rules.json",
    "disconnected_graph.json",
    "kde_bootstrap.json",
    "multiplicity.json",
    "odd_iterations.json",
    "random_state.json",
    "repeat_error_identity.json",
    "session.json",
    "source_assertions.json",
    "subtree_distance_source.json",
}


def read_json(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalize_r_version(version: str) -> tuple[int, ...]:
    """Match R's ``numeric_version`` treatment of dots and hyphens."""

    try:
        return tuple(
            int(component) for component in version.replace("-", ".").split(".")
        )
    except ValueError as error:
        raise RuntimeError(
            f"unsupported R package version spelling: {version}"
        ) from error


def verify_source_snapshot(root: Path) -> int:
    manifest = root / "validation/reference/choir_v0_3_0/SOURCE_MANIFEST.sha256"
    count = 0
    for line in manifest.read_text(encoding="utf-8").splitlines():
        expected, relative = line.split(maxsplit=1)
        path = root / relative.strip()
        actual = sha256(path)
        if actual != expected:
            raise RuntimeError(f"source checksum mismatch: {relative}")
        count += 1
    return count


def verify_fixture_manifest(root: Path, fixture_dir: Path) -> int:
    manifest_path = fixture_dir / "MANIFEST.json"
    manifest = read_json(manifest_path)
    listed = {Path(record["path"]).name for record in manifest["files"]}
    if listed != EXPECTED_FIXTURES:
        missing = sorted(EXPECTED_FIXTURES - listed)
        extra = sorted(listed - EXPECTED_FIXTURES)
        raise RuntimeError(
            f"fixture manifest mismatch; missing={missing}, extra={extra}"
        )
    for record in manifest["files"]:
        path = root / record["path"]
        if path.stat().st_size != record["bytes"]:
            raise RuntimeError(f"fixture size mismatch: {record['path']}")
        if sha256(path) != record["sha256"]:
            raise RuntimeError(f"fixture checksum mismatch: {record['path']}")
    return len(manifest["files"])


def verify_r_lock(root: Path, fixture_dir: Path) -> dict[str, str]:
    lock = read_json(root / "renv.lock")
    session = read_json(fixture_dir / "session.json")
    if lock["R"]["Version"] != "4.5.1":
        raise RuntimeError("renv.lock does not pin R 4.5.1")
    if not session["r_version"].startswith("R version 4.5.1 "):
        raise RuntimeError("fixtures were not generated by R 4.5.1")
    versions: dict[str, str] = session["packages"]
    for package, actual in versions.items():
        expected = lock["Packages"][package]["Version"]
        if normalize_r_version(actual) != normalize_r_version(expected):
            raise RuntimeError(
                f"R package drift for {package}: fixture={actual}, lock={expected}"
            )
    return versions


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--fixtures", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    root = args.root.resolve()
    fixture_dir = args.fixtures.resolve()
    source_file_count = verify_source_snapshot(root)
    fixture_file_count = verify_fixture_manifest(root, fixture_dir)
    versions = verify_r_lock(root, fixture_dir)

    assertions = read_json(fixture_dir / "source_assertions.json")
    failed = sorted(name for name, passed in assertions.items() if not passed)
    if failed:
        raise RuntimeError(f"frozen source assertions failed: {failed}")

    dataset_spec = root / "validation/fixtures/specs/datasets.yaml"
    text = dataset_spec.read_text(encoding="utf-8")
    required_dataset_tokens = (
        "cf2024b530fc9101b9f2d64998868541",
        "opened_for_calibration: false",
        "Simulated Dataset 111",
        "overall_decision_concordance_min: 0.95",
    )
    for token in required_dataset_tokens:
        if token not in text:
            raise RuntimeError(
                f"dataset specification is missing frozen token: {token}"
            )

    payload = {
        "schema_version": 1,
        "gate": 0,
        "status": "PASS",
        "reference_commit": "0db5e90ef46cd4f2f3765aa812325c8c768563fa",
        "source_files_verified": source_file_count,
        "fixture_files_verified": fixture_file_count,
        "r_version": "4.5.1",
        "r_packages": versions,
        "holdout_sealed": True,
        "limitations": [
            "Parent dataset archive is frozen by its Zenodo MD5; selected member "
            "SHA-256 values are required before calibration.",
            "Gate 0 is a design/reference gate and is not GPU functional evidence.",
        ],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_suffix(args.output.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    temporary.replace(args.output)


if __name__ == "__main__":
    main()
